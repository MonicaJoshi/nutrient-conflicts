class ReferenceAndConflictCommandTests(CliTestCase):
    def test_reference_build_and_status(self):
        payload = self.invoke_json("reference", "build")
        self.assertEqual(payload["merged"]["pairs"], 58)
        status = self.invoke_json("reference", "status")
        self.assertFalse(status["stale"], status["reasons"])
        self.assertEqual(status["merged"]["pairs"], 58)
        table = self.invoke("reference", "status")
        self.assertEqual(table.exit_code, 0, table.output)
        self.assertIn("merged KB", table.output)

    def test_reference_build_table_output(self):
        result = self.invoke("reference", "build")
        self.assertEqual(result.exit_code, 0, result.output)
        self.assertIn("reference data built", result.output)
        self.assertIn("merged KB", result.output)

    def test_reference_crosscheck_command(self):
        self.invoke_json("reference", "build")
        payload = self.invoke_json("reference", "crosscheck")
        self.assertIn("seed_pairs", payload)
        self.assertGreater(payload["merged_pairs"], 0)
        table = self.invoke("reference", "crosscheck")
        self.assertEqual(table.exit_code, 0, table.output)
        self.assertIn("generated", table.output)

    def test_reference_clear_removes_outputs(self):
        self.invoke_json("reference", "build")
        cleared = self.invoke_json("reference", "clear")
        self.assertTrue(cleared["removed"])
        self.assertGreaterEqual(cleared["cache_cleared"], 0)
        self.assertTrue(self.invoke_json("reference", "status")["stale"])
        self.invoke_json("reference", "build")

    def test_conflicts_build_show_and_status(self):
        payload = self.invoke_json("conflicts", "build", "--force")
        self.assertGreaterEqual(payload["rows"], 1)
        shown = self.invoke("conflicts", "show", "--brand", "Test Brand")
        self.assertEqual(shown.exit_code, 0, shown.output)
        self.assertIn("SUMMARY", shown.output)
        self.assertIn("WARNING", shown.output)
        self.assertIn("registered dietitian", shown.output)
        self.assertIn("Quantities involved", shown.output)
        status = self.invoke_json("conflicts", "status")
        self.assertTrue(status["exists"])
        self.assertFalse(status["stale"], status["reasons"])

    def test_conflicts_show_json_payload(self):
        self.invoke_json("conflicts", "build")
        payload = self.invoke_json("conflicts", "show", "--brand", "test brand")
        self.assertEqual(payload["brand_owner"], "Test Brand")
        self.assertTrue(payload["summary"]["conflicting"])
        self.assertTrue(payload["warning"]["required"])
        self.assertTrue(payload["nutrients"])

    def test_conflicts_clear_removes_results(self):
        self.invoke_json("conflicts", "build", "--force")
        cleared = self.invoke_json("conflicts", "clear")
        self.assertTrue(cleared["removed"])
        self.assertFalse(self.invoke_json("conflicts", "status")["exists"])
        self.invoke_json("conflicts", "build", "--force")

    def test_unknown_brand_conflicts_fails_cleanly(self):
        self.invoke_json("conflicts", "build")
        output = self.invoke_error("conflicts", "show", "--brand", "No Such Brand At All")
        self.assertIn("brand not found", output)


