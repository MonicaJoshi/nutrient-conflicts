"""CLI tests.

The CLI reads its configuration through ``NUTRIENTCONFLICTS_HOME``, so each test class
materialises a throw-away home directory holding an ``application.properties``
that points at the fixture dataset and at the store built for the class.
"""

from __future__ import annotations

import json
import shutil
import tempfile
import unittest
from pathlib import Path

from click.testing import CliRunner

from nutrient_conflicts.cli import main
from nutrient_conflicts.services import NutrientConflictsService
from support import fixture_config

PATH_KEYS = ("dataset.root", "reference.dir", "store.dir", "cache.dir")


class CliTestCase(unittest.TestCase):
    """Builds the fixture store once and gives every test a fresh runner."""

    @classmethod
    def setUpClass(cls) -> None:
        cls.workdir = Path(tempfile.mkdtemp(prefix="NutrientConflicts-cli-"))
        cls.home = cls.workdir / "home"
        cls.home.mkdir(parents=True, exist_ok=True)
        cls.config = fixture_config(cls.workdir)
        NutrientConflictsService(cls.config).ingest(force=True)
        cls._write_home_properties()

    @classmethod
    def _write_home_properties(cls) -> None:
        values = dict(cls.config.values)
        for key in ("dataset.root", "reference.dir", "reference.source.dir",
                    "store.dir", "cache.dir"):
            if key in values:
                values[key] = str(Path(values[key]).resolve())
        lines = ["# generated by tests/test_cli.py"]
        for key, value in values.items():
            lines.append(f"{key}={value}")
        (cls.home / "application.properties").write_text("\n".join(lines) + "\n", encoding="utf-8")

    @classmethod
    def tearDownClass(cls) -> None:
        shutil.rmtree(cls.workdir, ignore_errors=True)

    def setUp(self) -> None:
        self.runner = CliRunner(mix_stderr=False)
        self.env = {"NUTRIENTCONFLICTS_HOME": str(self.home)}

    def invoke(self, *args: str):
        return self.runner.invoke(main, list(args), env=self.env, catch_exceptions=False)

    def invoke_error(self, *args: str):
        """Run a command that is expected to fail and return its combined text."""
        result = self.invoke(*args)
        self.assertNotEqual(result.exit_code, 0, result.output)
        return result.output + (result.stderr or "")

    def invoke_json(self, *args: str):
        result = self.invoke(*args, "--json")
        self.assertEqual(result.exit_code, 0, result.output)
        return json.loads(result.output)


class HelpTests(CliTestCase):
    def test_group_help_is_available_for_both_flags(self):
        for flag in ("-h", "--help"):
            result = self.invoke(flag)
            self.assertEqual(result.exit_code, 0, result.output)
            self.assertIn("NutrientConflicts", result.output)
            for command in ("ingest", "search", "evaluate", "interactions", "reference",
                            "conflicts", "gui", "serve"):
                self.assertIn(command, result.output)

    def test_subcommand_help(self):
        result = self.invoke("evaluate", "--help")
        self.assertEqual(result.exit_code, 0, result.output)
        self.assertIn("--fdc-id", result.output)
        self.assertIn("--nutrients", result.output)


